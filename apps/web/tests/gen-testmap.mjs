// Generate tests/TESTMAP.md — the committed, human-readable map from each
// E2E-NN scenario to its test title, test file, primary spec, requirements, and
// recording filename. Everything is derived from spec-map.json + /spec, so the
// table never drifts. Runs without a recording.
//
// Usage, from apps/web:  node tests/gen-testmap.mjs

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
// Node 22.18+ runs the TypeScript module directly (type stripping), so the
// scenario data and the /spec parser are single-sourced in spec-map.ts.
import { SCENARIOS, primarySpec, requirement, videoName } from "./spec-map.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "TESTMAP.md");

const scenarios = SCENARIOS;

const lines = [];
lines.push("# E2E test ↔ spec map");
lines.push("");
lines.push(
  "Generated by `node tests/gen-testmap.mjs` from `tests/spec-map.json` + `/spec` —",
  "do not edit by hand. Each scenario has a stable `E2E-NN` id that appears in the",
  "Playwright test title, the recording filename, and this table.",
);
lines.push("");
lines.push("| ID | Test | Test file | Primary spec | Requirements | Recording |");
lines.push("|----|------|-----------|--------------|--------------|-----------|");
for (const s of scenarios) {
  const reqs = s.requirements.join(", ");
  const tag = s.new === true ? " **(new)**" : "";
  lines.push(
    `| ${s.id} | ${s.title}${tag} | \`tests/${s.testFile}\` | ` +
      `[\`${primarySpec(s.id)}\`](../../../spec/${primarySpec(s.id)}) | ` +
      `${reqs} | \`${videoName(s.id)}\` |`,
  );
}
lines.push("");
lines.push("## Requirements referenced");
lines.push("");
lines.push("| Requirement | Spec | Statement |");
lines.push("|-------------|------|-----------|");
const seen = new Set();
for (const s of scenarios) {
  for (const id of s.requirements) {
    if (seen.has(id)) continue;
    seen.add(id);
    const r = requirement(id);
    const text = r.text.length > 160 ? `${r.text.slice(0, 157)}…` : r.text;
    lines.push(`| ${id} | \`${r.spec}\` | ${text.replace(/\|/g, "\\|")} |`);
  }
}
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${OUT} (${scenarios.length} scenarios, ${seen.size} requirements)`);
